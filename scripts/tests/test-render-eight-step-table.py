#!/usr/bin/env python3
"""Tests for the bilingual eight-step table renderer."""

from __future__ import annotations

import importlib.util
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
RENDERER = ROOT / "scripts" / "render-eight-step-table.py"


def load_renderer():
    spec = importlib.util.spec_from_file_location("render_eight_step_table", RENDERER)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def table_rows(text: str) -> int:
    return sum(1 for line in text.splitlines()
               if line.startswith("|") and "---" not in line)


def main() -> int:
    failures = 0
    cases = 0

    def check(label: str, ok: bool, detail: str = "") -> None:
        nonlocal failures, cases
        cases += 1
        print(f"{'PASS' if ok else 'FAIL'} {label}")
        if not ok:
            failures += 1
            if detail:
                print("      " + detail)

    renderer = load_renderer()
    renderer.DATA = str(ROOT / "docs" / "research" / "EIGHT-STEPS.toml")
    zh = renderer.render("zh")
    en = renderer.render("en")

    check("Chinese table keeps the Chinese touch name",
          "触摸（Goodix GT9916R / BERLIN）" in zh)
    check("English table translates the touch name",
          "Touch (Goodix GT9916R / BERLIN)" in en)
    check("English table translates the charger name",
          "Charger / battery protocol (qti_battery_charger + pmic_glink)" in en)
    check("English table has no Chinese characters",
          re.search(r"[\u4e00-\u9fff]", en) is None,
          "found: " + ", ".join(re.findall(r"[\u4e00-\u9fff]+", en)))
    check("English footer is translated",
          "The table is generated by" in en and "八步定义" not in en)
    check("English untracked rows use English labels",
          "| Power |" in en and "| Diagnostics |" in en and "| Baseband |" in en)
    check("Chinese and English tables have the same row count",
          table_rows(zh) == table_rows(en),
          f"zh={table_rows(zh)} en={table_rows(en)}")

    if failures:
        print(f"TESTS OK 0 cases ({failures} failure(s))")
        return 1
    print(f"TESTS OK {cases} cases (0 failure(s))")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
