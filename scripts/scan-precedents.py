#!/usr/bin/env python3
"""Enumerate every artefact of the working iOS 27 repositories.

The point is that the item list is *scanned*, not authored: if a precedent
repository adds a patch or a config key, the count changes and
`check-goal-constraints.py` refuses to build until the new item is classified.

Output: docs/research/ios27/PRECEDENT-MANIFEST.toml with one [[repo]] per
repository, `measured_items`, and one [[repo.item]] per artefact:
  kind  = "patch" | "board-key" | "defconfig-key"
  id    = stable identifier
  sha256= content hash (patches), or "" for keys
  verdict = "have" | "copied" | "not-applicable" | "unknown"

The scanner preserves verdicts and reasons for items that were already judged
and whose patch hash is unchanged. A new patch, or a changed patch body, is
emitted as `unknown` on purpose: it must be read and classified again.

Read-only with respect to the precedent repositories.
"""
from __future__ import annotations

import collections
import hashlib
import pathlib
import sys
import tomllib

REPOS = {
    'asteroids': '/mnt/e/iOS Port/Work/references/community/asteroids',
    'uke': '/mnt/e/iOS Port/Work/references/community/uke',
    'cupid': '/mnt/e/iOS Port/Work/references/community/cupid',
    'vermeer': '/mnt/e/iOS Port/Work/references/community/vermeer',
    # The three same-SoC sources are scanned from read-only reference exports,
    # not from the older working checkouts: the export's .reference-commit names
    # the exact commit it was taken from.
    'sheng': '/mnt/e/iOS Port/Work/references/latest/UniXNU-sheng',
    't970': '/mnt/e/iOS Port/Sources/Repos/UniXNU/UniXNU-t970',
    'zizhan': '/mnt/e/iOS Port/Work/references/latest/UniXNU-zizhan',
    'pong': '/mnt/e/iOS Port/Work/references/latest/UniXNU-pong',
    'ios16': str(pathlib.Path(__file__).resolve().parents[1]),
}
OURS = pathlib.Path(__file__).resolve().parents[1]
OUT = OURS / 'docs/research/ios27/PRECEDENT-MANIFEST.toml'

DEFAULT_PATCH_DIRS = ('patches/xnu-12377', 'patches/xnu')
LAYOUT = {
    't970': {'patch_dirs': ('patches/xnu-ipados18',),
             'defconfig': 'configs/pong_ipados18_defconfig'},
    'zizhan': {'patch_dirs': ('patches/xnu-ipados18',),
               'defconfig': 'configs/zizhan_ipados18_gpu_defconfig'},
    'pong': {'patch_dirs': ('patches/xnu-ios18e',),
             'defconfig': 'configs/pong_ios18e_defconfig'},
    # Our own iOS 16 line: only patches/xnu, and no board/defconfig keys
    # (they are already this repository's own values, not a precedent).
    'ios16': {'patch_dirs': ('patches/xnu',), 'defconfig': None, 'board': False},
}


def flatten(prefix: str, value, out: list[str]) -> None:
    if isinstance(value, dict):
        for key, child in value.items():
            flatten(f'{prefix}.{key}' if prefix else key, child, out)
    else:
        out.append(prefix)


def board_keys(path: pathlib.Path) -> list[str]:
    if not path.is_file():
        return []
    data = tomllib.loads(path.read_text(encoding='utf-8'))
    keys: list[str] = []
    for section, value in data.items():
        flatten(section, value, keys)
    return sorted(keys)


def defconfig_keys(path: pathlib.Path) -> list[str]:
    if not path.is_file():
        return []
    keys = []
    for line in path.read_text(encoding='utf-8', errors='replace').splitlines():
        line = line.strip()
        if line.startswith('CONFIG_') and '=' in line:
            keys.append(line.split('=', 1)[0])
    return sorted(set(keys))


def patches(repo: pathlib.Path, name: str) -> list[pathlib.Path]:
    found = []
    for directory in LAYOUT.get(name, {}).get('patch_dirs', DEFAULT_PATCH_DIRS):
        base = repo / directory
        if base.is_dir():
            found.extend(sorted(base.glob('*.patch')))
    return found


def old_manifest() -> dict[str, dict]:
    if not OUT.is_file():
        return {}
    data = tomllib.loads(OUT.read_text(encoding='utf-8'))
    return {repo['name']: repo for repo in data.get('repo', [])}


def emit_item(lines: list[str], item: dict) -> None:
    lines.append('  [[repo.item]]')
    for key in ('kind', 'id', 'sha256'):
        if item.get(key):
            lines.append(f'  {key} = ' + quote(item[key]))
    lines.append('  verdict = ' + quote(item['verdict']))
    if item.get('reason'):
        lines.append('  reason = ' + quote(item['reason']))
    lines.append('')


def quote(value: str) -> str:
    import json
    return json.dumps(value, ensure_ascii=False)


HEADER = [
    '# Generated by scripts/scan-precedents.py — do not hand-edit.',
    '# verdict: have = present in our tree; copied = landed in our 27 series;',
    '# not-applicable = precedent-specific/dead in the 27 build, with evidence in reason.',
    '',
]


def dump_manifest(data: dict) -> str:
    """Serialise the whole ledger from the in-memory structure."""
    lines = list(HEADER)
    for repo in data['repo']:
        lines.append('[[repo]]')
        lines.append('name = ' + quote(repo['name']))
        lines.append('path = ' + quote(repo['path']))
        if repo.get('commit'):
            lines.append('commit = ' + quote(repo['commit']))
        lines.append('measured_items = ' + str(repo['measured_items']))
        lines.append('')
        for item in repo['item']:
            emit_item(lines, item)
    return '\n'.join(lines)


def reference_commit(repo: pathlib.Path) -> str:
    marker = repo / '.reference-commit'
    if not marker.is_file():
        return ''
    return marker.read_text(encoding='utf-8').strip()


def main() -> int:
    our_board = set(board_keys(OURS / 'board.toml'))
    our_defconfig = set(defconfig_keys(OURS / 'configs/mondrian_ios27_defconfig'))
    previous = old_manifest()
    repositories: list[dict] = []
    summary = []
    total = 0
    for name, path in REPOS.items():
        repo = pathlib.Path(path)
        if not repo.is_dir():
            summary.append(f'{name}: MISSING REPOSITORY at {path}')
            continue
        old_items = collections.defaultdict(collections.deque)
        for item in previous.get(name, {}).get('item', []):
            old_items[(item.get('kind'), item.get('id'))].append(item)

        items: list[dict] = []

        def reuse(kind: str, ident: str, digest: str, fallback: str) -> dict:
            pool = old_items[(kind, ident)]
            item: dict = {'kind': kind, 'id': ident}
            if digest:
                item['sha256'] = digest
            if not pool:
                item['verdict'] = fallback
                return item
            old = pool.popleft()
            if kind == 'patch' and old.get('sha256') != digest:
                item['verdict'] = 'unknown'
                return item
            item['verdict'] = old.get('verdict', fallback)
            if old.get('reason'):
                item['reason'] = old['reason']
            return item

        for patch in patches(repo, name):
            digest = hashlib.sha256(patch.read_bytes()).hexdigest()
            items.append(reuse('patch', patch.name, digest, 'unknown'))
        if LAYOUT.get(name, {}).get('board', True):
            for key in board_keys(repo / 'board.toml'):
                items.append(reuse('board-key', key, '', 'have' if key in our_board else 'unknown'))
        cfg_name = LAYOUT.get(name, {}).get('defconfig')
        if cfg_name is None and name not in LAYOUT:
            cfg = repo / 'configs' / f'{name}_ipados27_defconfig'
            if not cfg.is_file():
                candidates = sorted((repo / 'configs').glob('*27*defconfig')) if (repo / 'configs').is_dir() else []
                cfg = candidates[0] if candidates else cfg
            cfg_name = str(cfg.relative_to(repo)) if cfg.is_file() else None
        if cfg_name:
            for key in defconfig_keys(repo / cfg_name):
                items.append(reuse('defconfig-key', key, '', 'have' if key in our_defconfig else 'unknown'))

        block = {'name': name, 'path': path, 'measured_items': len(items), 'item': items}
        commit = reference_commit(repo)
        if commit:
            block['commit'] = commit
        repositories.append(block)
        unknown = sum(1 for item in items if item['verdict'] == 'unknown')
        total += len(items)
        summary.append(f'{name}: {len(items)} items, {unknown} unknown')

    data = {'repo': repositories}
    text = dump_manifest(data)
    # Structured write contract: read -> mutate in memory -> serialise -> parse back.
    reloaded = tomllib.loads(text)
    if reloaded != data:
        raise SystemExit('refusing to write: TOML round-trip does not match the in-memory ledger')
    temporary = OUT.with_suffix('.toml.tmp')
    temporary.write_text(text, encoding='utf-8')
    temporary.replace(OUT)
    print('\n'.join(summary))
    print(f'\n{total} items across {len(repositories)} repositories')
    print(f'wrote {OUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
