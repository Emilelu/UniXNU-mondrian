#!/usr/bin/env python3
"""Embed the captured ADSP image files into the kernel as one K60A container.

The production container ABI is fixed (Lead ruling, P-197): a 12-byte header,
one 24-byte record per file, NUL-terminated names, every name and body starting
on an 8-byte boundary, and one cursor that yields the total length including
all alignment padding. There is no compression and no second container shape.

    python3 scripts/gen-k60-adsp-blob.py --firmware-dir <adsp dir> \
        --output <tree>/k60_adsp_blob.s

The assembly embeds the header/records/names as .byte and the bodies through
.incbin, so the 23.5 MB container never becomes a huge C translation unit.
_k60_adsp_blob_len is the final cursor, not the sum of raw body sizes (P-196:
the Metal deploy failed exactly that way).
"""
import argparse
import hashlib
import struct
from pathlib import Path

MAGIC = b'K60A'
HEADER = struct.Struct('<4sII')     # magic, count, reserved
RECORD = struct.Struct('<IIQQ')     # name_len incl NUL, mode, size, packed_size
ALIGN = 8
MODE = 0o644
UINT32_MAX = (1 << 32) - 1

# The captured mirror has exactly these 26 image files: the MDT plus b00..b25
# with b24 absent (pure BSS, no file exists and none must be invented). The
# two JSON sidecars (adspr.jsn/adspua.jsn) are not part of the image.
PIECES = tuple('adsp.b%02d' % i for i in range(26) if i != 24)
NAMES = ('adsp.mdt',) + PIECES


def align(n: int) -> int:
    return (n + ALIGN - 1) & ~(ALIGN - 1)


def load(firmware: Path):
    entries = []
    for name in NAMES:
        path = firmware / name
        if not path.is_file():
            raise SystemExit(f'missing input: {path}')
        if path.stat().st_size > UINT32_MAX:
            raise SystemExit(f'input exceeds reader bounds: {path}')
        body = path.read_bytes()
        if not body:
            raise SystemExit(f'empty input: {path}')
        entries.append((name.encode() + b'\0', body))
    return entries


def build(entries):
    """Lay the container out with the same cursor the kernel/checker uses."""
    if not 1 <= len(entries) <= 64:
        raise ValueError('entry count must be in 1..64')
    cursor = HEADER.size
    seen = set()
    for name, body in entries:
        if name not in {n.encode('ascii') + b'\0' for n in NAMES} or name in seen:
            raise ValueError('noncanonical or duplicate input name')
        seen.add(name)
        cursor = align(align(cursor + RECORD.size) + len(name))
        cursor = align(cursor + len(body))
        if not body or cursor > UINT32_MAX:
            raise ValueError('empty input or container exceeds reader bounds')
    blob = bytearray(HEADER.size)
    for name, body in entries:
        blob += RECORD.pack(len(name), MODE, len(body), len(body))
        blob += b'\0' * (align(len(blob)) - len(blob))
        blob += name
        blob += b'\0' * (align(len(blob)) - len(blob))
        blob += body
        blob += b'\0' * (align(len(blob)) - len(blob))
    HEADER.pack_into(blob, 0, MAGIC, len(entries), 0)
    return bytes(blob)


def emit_source(blob: bytes, entries, firmware: Path, output: Path) -> None:
    lines = ['/* Generated by scripts/gen-k60-adsp-blob.py - do not edit. */',
             '.data',
             '.globl _k60_adsp_blob',
             '.p2align 3',
             '_k60_adsp_blob:']
    # Emit the header and each record/name run as .byte, and each body through
    # .incbin followed by .p2align 3. Every .p2align here reproduces exactly
    # the zero padding that build() counted into the cursor.
    def byte_run(start, end):
        for at in range(start, end, 16):
            chunk = blob[at:min(at + 16, end)]
            lines.append('    .byte ' + ','.join('0x%02x' % b for b in chunk))

    cursor = 0
    byte_run(0, HEADER.size)
    cursor = HEADER.size
    for name, body in entries:
        byte_run(cursor, cursor + RECORD.size)
        cursor = align(cursor + RECORD.size)
        lines.append('    .p2align 3')
        byte_run(cursor, cursor + len(name))
        cursor = align(cursor + len(name))
        lines.append('    .p2align 3')
        path = (firmware / name.decode()[:-1]).resolve().as_posix()
        if any(c in path for c in '"\\\r\n'):
            raise ValueError('firmware path is not representable in .incbin')
        lines.append('    .incbin "%s"' % path)
        cursor = align(cursor + len(body))
        lines.append('    .p2align 3')
    total = len(blob)
    lines += ['', '.globl _k60_adsp_blob_len', '.p2align 3',
              '_k60_adsp_blob_len:', '    .quad %d' % total]
    output.write_text('\n'.join(lines) + '\n', encoding='utf-8')


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--firmware-dir', type=Path, required=True,
                        help='directory holding adsp.mdt and adsp.bNN')
    parser.add_argument('--output', type=Path, required=True,
                        help='generated assembly file (k60_adsp_blob.s)')
    parser.add_argument('--dump', type=Path,
                        help='also write the raw container bytes here')
    args = parser.parse_args()
    entries = load(args.firmware_dir)
    blob = build(entries)
    emit_source(blob, entries, args.firmware_dir, args.output)
    digest = hashlib.sha256(blob).hexdigest()
    raw = sum(len(body) for _, body in entries)
    print('%s: %d bytes, %d records, raw %d, sha256 %s'
          % (args.output, len(blob), len(entries), raw, digest))
    if args.dump:
        args.dump.write_bytes(blob)
        print('dumped %d raw bytes to %s' % (len(blob), args.dump))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
