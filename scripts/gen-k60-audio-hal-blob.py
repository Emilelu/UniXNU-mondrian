#!/usr/bin/env python3
"""Embed the PongAudio AudioServerPlugIn into the kernel as one deployable blob.

The bundle has to exist on the Data volume before init bind-mounts the HAL
directory: the sealed root volume is read-only and no host tool here can write
APFS inside the unixnu partition.  The existing empty-hal directory in
/private/var/pong is the bind source, so the kernel can populate it after the
Data mount just as 0340 and 0394 populate their payloads.

The container is a flat table followed by the file bodies:

    uint32  magic 'K60A'
    uint32  count
    count x { uint16 name_len, uint32 size, uint32 offset }   (offsets from 0)
    count x name (no terminator)
    <bodies, 8-byte aligned>

Usage:
    python3 scripts/gen-k60-audio-hal-blob.py --bundle-dir <PongAudio.driver> \
        --assembly --output <file.s>
    python3 scripts/gen-k60-audio-hal-blob.py --empty --assembly --output <file.s>
"""
import argparse
import struct
from pathlib import Path

MAGIC = b'K60A'
HEADER = struct.Struct('<4sI')
ENTRY = struct.Struct('<HII')
ALIGN = 8

# Order matters: the Info.plist is written before the executable, and the modes
# list below matches this order exactly.
FILES = (
    ('PongAudio.driver/Info.plist', 0o644),
    ('PongAudio.driver/PongAudio', 0o755),
)


def emit_source(files, output: Path) -> None:
    names = b''.join(name for name, _, _ in files)
    base = (HEADER.size + ENTRY.size * len(files) + len(names) + ALIGN - 1) & ~(ALIGN - 1)
    offsets, cursor = [], base
    for _, size, _ in files:
        offsets.append(cursor)
        cursor += (size + ALIGN - 1) & ~(ALIGN - 1)
    table = b''.join(ENTRY.pack(len(name), size, offsets[i])
                     for i, (name, size, _) in enumerate(files))
    head = HEADER.pack(MAGIC, len(files)) + table + names
    head += b'\0' * (base - len(head))

    lines = ['/* Generated by scripts/gen-k60-audio-hal-blob.py - do not edit. */',
             '.data',
             '.globl _k60_audio_hal_blob',
             '.p2align 3',
             '_k60_audio_hal_blob:']
    for start in range(0, len(head), 16):
        chunk = head[start:start + 16]
        lines.append('    .byte ' + ','.join('0x%02x' % b for b in chunk))
    for _, _, path in files:
        lines.append('    .incbin "%s"' % path)
        lines.append('    .p2align 3')
    lines += ['', '.globl _k60_audio_hal_blob_len', '.p2align 3',
              '_k60_audio_hal_blob_len:', '    .quad %d' % cursor]
    modes = [mode for _, mode in FILES]
    lines += ['', '.globl _k60_audio_hal_blob_modes', '.p2align 3',
              '_k60_audio_hal_blob_modes:', '    .short ' + ','.join('0%o' % m for m in modes)]
    output.write_text('\n'.join(lines) + '\n')


def main() -> int:
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--bundle-dir', type=Path,
                       help='directory containing Info.plist and PongAudio')
    group.add_argument('--empty', action='store_true',
                       help='emit a table with zero entries')
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--assembly', action='store_true',
                       help='emit an assembly file using .incbin instead of a C array')
    args = parser.parse_args()
    if not args.assembly:
        parser.error('this generator only emits assembly; pass --assembly')

    files = []
    if not args.empty:
        for rel, _ in FILES:
            source = args.bundle_dir / rel.replace('PongAudio.driver/', '')
            if not source.is_file():
                raise SystemExit('missing input: ' + str(source))
            files.append((rel.encode(), source.stat().st_size, source.resolve()))
    emit_source(files, args.output)
    print('%s: %d bodies, %d bytes of header' % (args.output, len(files), 8 + 10 * len(files)))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
