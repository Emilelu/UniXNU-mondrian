"""Emit the modem (MSS) segment table as a C header for the PAS loader.

Input: a directory holding modem.mdt and modem.b00..b31, pulled from the device
with 'adb exec-out' (byte exact). 'adb shell' rewrites CRLF and corrupts modem.mdt,
so the dump keeps a .bin suffix; this script accepts either spelling.

Output: a header with one row per PT_LOAD segment plus the base/window facts, so
the loader never parses ELF at boot and cannot disagree with the offline test.

Why a table instead of parsing at boot: same reason as scripts/gen-adsp-table.py.
The bytes are fixed by the shipped firmware, the check belongs in a host test, and
a table that disagrees with the firmware fails the test instead of failing a boot.

Run: python3 scripts/gen-modem-table.py /mnt/e/k60-work/firmware/modem drivers/PongCellular/pong_modem_table.h
"""

import struct
import sys
from pathlib import Path

# From the live Android DT: /reserved-memory/mpss_region@8bc00000
# reg = <0x00 0x8bc00000 0x00 0x13200000>  (306 MiB)
BASE = 0x8bc00000
WINDOW = 0x13200000


def find(root, name):
    """Prefer the .bin spelling.

    The byte-exact dump is written as name.bin because 'adb exec-out' output is
    redirected through a shell that would otherwise be tempted to rewrite it. A
    plain 'adb shell cat' copy of the same file also exists on this machine and
    is CRLF-mangled (modem.b01 is 7232 bytes there, 7204 here), so the suffix is
    not cosmetic: preferring the unsuffixed name silently feeds the generator a
    corrupt image and it fails with a size mismatch.
    """
    suffixed = root / (name + ".bin")
    if suffixed.is_file():
        return suffixed
    exact = root / name
    if exact.is_file():
        return exact
    return None


def rows(root):
    mdt_path = find(root, "modem.mdt")
    if mdt_path is None:
        raise SystemExit("modem.mdt is missing from %s" % root)
    mdt = mdt_path.read_bytes()
    if mdt[:4] != b"\x7fELF" or mdt[4] != 1:
        raise SystemExit("modem.mdt is not ELF32")
    phoff, = struct.unpack_from("<I", mdt, 28)
    phentsize, phnum = struct.unpack_from("<HH", mdt, 42)
    if phentsize != 32:
        raise SystemExit("unexpected e_phentsize %d" % phentsize)
    out = []
    for i in range(phnum):
        off = phoff + i * phentsize
        p_type, p_offset, _vaddr, p_paddr, p_filesz, p_memsz = struct.unpack_from("<6I", mdt, off)
        if p_type != 1:
            continue
        name = "modem.b%02d" % i
        filesz = 0
        if p_filesz:
            part = find(root, name)
            if part is None:
                raise SystemExit("%s missing although the table declares %d bytes" % (name, p_filesz))
            have = part.stat().st_size
            if have != p_filesz:
                raise SystemExit("%s is %d bytes, table says %d" % (name, have, p_filesz))
            if p_offset % 4096:
                raise SystemExit("%s has a non page-aligned file offset %#x" % (name, p_offset))
            if p_memsz < p_filesz:
                raise SystemExit("%s declares memsz %d < filesz %d" % (name, p_memsz, p_filesz))
            filesz = p_filesz
        out.append((i, name, p_paddr, filesz, p_memsz - filesz))
    if not out:
        raise SystemExit("modem.mdt has no PT_LOAD segment")
    return out


def main(argv):
    if len(argv) < 3:
        raise SystemExit("usage: gen-modem-table.py <firmware-dir> <header-out>")
    root = Path(argv[1])
    dest = Path(argv[2])
    table = rows(root)

    lines = []
    lines.append("/* Generated by scripts/gen-modem-table.py from the shipped modem.mdt. Do not edit. */")
    lines.append("/* Rows use K60ModemSegment from K60ModemImage.h. */")
    lines.append("#define K60_MODEM_BASE 0x%08xUL" % BASE)
    lines.append("#define K60_MODEM_WINDOW 0x%08xUL" % WINDOW)
    lines.append("#define K60_MODEM_SEGMENTS %d" % len(table))
    lines.append("")
    lines.append("static const K60ModemSegment k60_modem_segments[K60_MODEM_SEGMENTS] = {")
    for index, name, paddr, filesz, bss in table:
        part = '"%s"' % name if filesz else "((const char *)0)"
        lines.append("    { 0x%08xUL, %9d, %9d, %s }, /* segment %d */"
                     % (paddr, filesz, bss, part, index))
    lines.append("};")
    lines.append("")
    dest.write_text("\n".join(lines) + "\n", encoding="utf-8")

    lo = min(r[2] for r in table)
    hi = max(r[2] + r[3] + r[4] for r in table)
    print("rows %d  bytes-copied %d  bss %d  span %#x..%#x (%d, window %#x)"
          % (len(table), sum(r[3] for r in table), sum(r[4] for r in table), lo, hi, hi - lo, WINDOW))
    if lo != BASE or hi - lo > WINDOW:
        print("FAIL span does not fit the declared window")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
