#!/usr/bin/env python3
"""Emit a stub LegacyDisplayProbe.cpp from the component's own declarations.

Every extern "C" declaration of a native_legacy_* hook that the component does
not define becomes a definition with the same signature and an empty body.  The
stub is a starting point: it makes the symbol set complete so --probe reports
zero missing, but an empty body is not an implementation.  Each stub is marked
K60_PROBE_TODO so an audit can count what is still a placeholder.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

DECL = re.compile(r'extern\s+"C"\s+([^;{}]*?\b(native_legacy_[a-z0-9_]+)\s*\([^;{}]*\))\s*;')


def main(argv: list[str]) -> int:
    component = Path(argv[0] if argv else "/mnt/e/iOS Port/Work/references/GopFramebuffer")
    out = Path(argv[1] if len(argv) > 1 else "kits/mondrian/LegacyDisplayProbe.cpp")
    text = (component / "NativeLegacyDisplay.cpp").read_text() + (component / "NativeGOPPresenter.cpp").read_text()
    defined = set()
    for line in text.splitlines():
        m = re.search(r"\b(native_legacy_[a-z0-9_]+)\s*\([^;]{0,400}\)\s*(?:const\s*)?\{", line)
        if m and not re.search(r"\b(?:if|while|for|switch)\s*\(", line):
            defined.add(m.group(1))
    lines = ['// Generated by scripts/gen-display-probe-stubs.py.',
             '// K60_PROBE_TODO: every body below is empty; count them before shipping.',
             '#include <IOKit/IOService.h>', '', 'extern "C" {', '']
    seen = set()
    for sig, name in DECL.findall(text):
        if name in defined or name in seen:
            continue
        seen.add(name)
        lines.append(f"{sig} {{ /* K60_PROBE_TODO */ }}")
    lines += ['', '}  // extern "C"', '']
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"gen-display-probe-stubs: {len(seen)} stub(s) -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
