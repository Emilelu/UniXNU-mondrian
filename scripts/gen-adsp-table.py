"""Emit the ADSP segment table as a C header for the PAS1 loader.

Input: a directory with adsp.mdt and adsp.b00..b25 (pulled from the device).
Output: a header with one 24-byte row per PT_LOAD segment plus the base/size facts,
so the loader never parses ELF at boot and cannot disagree with the test.

Run: python3 scripts/gen-adsp-table.py /mnt/e/k60-work/firmware/adsp /tmp/pong_adsp_table.h
"""

import struct
import sys
from pathlib import Path

BASE = 0x86300000
WINDOW = 0x3100000


def rows(root):
    mdt = (root / "adsp.mdt").read_bytes()
    if mdt[:4] != b"\x7fELF" or mdt[4] != 1:
        raise SystemExit("adsp.mdt is not ELF32")
    phoff, = struct.unpack_from("<I", mdt, 28)
    phentsize, phnum = struct.unpack_from("<HH", mdt, 42)
    out = []
    for i in range(phnum):
        off = phoff + i * phentsize
        p_type, p_offset, _vaddr, p_paddr, p_filesz, p_memsz = struct.unpack_from("<6I", mdt, off)
        if p_type != 1:
            continue
        name = "adsp.b%02d" % i
        have = filesz = 0
        if p_filesz:
            part = root / name
            if not part.is_file():
                raise SystemExit("%s missing although the table declares %d bytes" % (name, p_filesz))
            have = part.stat().st_size
            if have != p_filesz:
                raise SystemExit("%s is %d bytes, table says %d" % (name, have, p_filesz))
            filesz = p_filesz
        out.append((i, name, p_paddr, filesz, p_memsz - filesz))
    return out


def main(argv):
    root = Path(argv[1])
    dest = Path(argv[2])
    table = rows(root)

    lines = []
    lines.append("/* Generated by scripts/gen-adsp-table.py from the shipped adsp.mdt. Do not edit. */")
    lines.append("#define K60_ADSP_BASE 0x%08xUL" % BASE)
    lines.append("#define K60_ADSP_WINDOW 0x%08xUL" % WINDOW)
    lines.append("#define K60_ADSP_SEGMENTS %d" % len(table))
    lines.append("")
    lines.append("static const struct k60_adsp_segment {")
    lines.append("    uint32_t paddr;")
    lines.append("    uint32_t bytes;   /* bytes to copy from the file */")
    lines.append("    uint32_t bss;     /* extra bytes to zero after the copy */")
    lines.append("    const char *part; /* NULL means the segment is pure bss */")
    lines.append("} k60_adsp_segments[K60_ADSP_SEGMENTS] = {")
    for index, name, paddr, filesz, bss in table:
        part = '"%s"' % name if filesz else "((const char *)0)"
        lines.append("    { 0x%08xUL, %8d, %8d, %s }, /* segment %d */"
                     % (paddr, filesz, bss, part, index))
    lines.append("};")
    lines.append("")
    dest.write_text("\n".join(lines) + "\n", encoding="utf-8")

    lo = min(r[2] for r in table)
    hi = max(r[2] + r[3] + r[4] for r in table)
    print("rows %d  bytes-copied %d  bss %d  span %#x..%#x (%d, window %#x)"
          % (len(table), sum(r[3] for r in table), sum(r[4] for r in table), lo, hi, hi - lo, WINDOW))
    if lo != BASE or hi - lo > WINDOW:
        print("FAIL span does not fit the declared window")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
