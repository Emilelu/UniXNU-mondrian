#!/usr/bin/env python3
'''Inventory our own ios16 kernel patches against the ios27 line.

Reads patches/xnu/zzzz*.patch, extracts the boot-args it introduces and the
functions it adds, and looks for them in patches/xnu-12377/** and in the
assembled ios27 tree.  Emits docs/research/ios27/IOS16-CARRYOVER.toml with one
[[patch]] entry per file.  A patch can only be 'carried' when every symbol it
introduces exists on the 27 side; anything else needs a human verdict
(deferred / not-applicable) or the gate refuses the build.
'''
import argparse, pathlib, re, subprocess, tomllib

REPO = pathlib.Path(__file__).resolve().parents[1]

def symbols(text):
    args = sorted(set(re.findall(r'PE_parse_boot_argn\("([^"]+)"', text)))
    funcs = set()
    for line in text.splitlines():
        if line.startswith('+') and not line.startswith('+++'):
            m = re.match(r'\+\s*(?:static\s+)?(?:[\w\*]+\s+)+([a-z_][A-Za-z0-9_]*)\s*\(', line)
            if m:
                funcs.add(m.group(1))
    return args, sorted(funcs)

def present(token, blob, tree):
    if token in blob:
        return True
    if tree and tree.is_dir():
        return subprocess.run(['grep', '-rq', token, str(tree)], capture_output=True).returncode == 0
    return False

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--tree', help='assembled xnu source tree (tree/.cache/xnu-work)')
    ap.add_argument('--write', action='store_true')
    opts = ap.parse_args()
    tree = pathlib.Path(opts.tree) if opts.tree else None
    target = REPO / 'patches/xnu-12377'
    blob = ''.join(p.read_text(errors='ignore') for p in target.glob('*.patch')) if target.is_dir() else ''
    rows = []
    for patch in sorted((REPO / 'patches/xnu').glob('zzzz*.patch')):
        text = patch.read_text(errors='ignore')
        args, funcs = symbols(text)
        miss_args = [a for a in args if not present(a, blob, tree)]
        miss_funcs = [f for f in funcs if not present(f, blob, tree)]
        if not args and not funcs:
            status = 'no-symbols'
        elif not miss_args and not miss_funcs:
            status = 'carried'
        elif len(miss_args) < len(args) or len(miss_funcs) < len(funcs):
            status = 'partial'
        else:
            status = 'missing'
        rows.append((patch.name, status, miss_args, miss_funcs))
    counts = {}
    for _, status, _, _ in rows:
        counts[status] = counts.get(status, 0) + 1
    print(' '.join(f'{k}={v}' for k, v in sorted(counts.items())))
    if opts.write:
        out = ['# Generated by scripts/audit-ios16-carryover.py.  A patch listed here',
               '# must carry a human verdict before the gate passes:', '#    verdict = carried | deferred | not-applicable', '']
        for name, status, miss_args, miss_funcs in rows:
            out.append('[[patch]]')
            out.append(f'name = {name}')
            out.append(f'detected = {status}')
            if miss_args:
                out.append('missing_args = [' + ', '.join(f'{a}' for a in miss_args) + ']')
            if miss_funcs:
                out.append('missing_functions = [' + ', '.join(f'{f}' for f in miss_funcs) + ']')
            out.append('')
        dest = REPO / 'docs/research/ios27/IOS16-CARRYOVER.toml'
        dest.write_text('\n'.join(out))
        print(f'wrote {dest.relative_to(REPO)} ({len(rows)} entries)')

if __name__ == '__main__':
    main()
