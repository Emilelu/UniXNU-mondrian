#!/bin/bash
# Offline only: never accesses a device or physical memory.
#
# usage: run-k60-handoff-host.sh DURABLE_OUTPUT PRE_0619_XNU_TREE
#
# PRE_0619_XNU_TREE must be a .cache/xnu-work tree that predates 0619/0620: the
# integration cases below apply the 0611 predecessor of the handoff pair
# themselves, so a tree that already carries 0619 fails halfway with
# "canonical source differs" - a message that points at the code instead of at
# the input. The check below refuses such a tree up front and says why.
set -euo pipefail
REPO=$(cd "$(dirname "$0")/../.." && pwd)
OUT=${1:?usage: run-k60-handoff-host.sh DURABLE_OUTPUT PRE_0619_XNU_TREE}
XNU=${2:?a supported pre-0619 .cache/xnu-work tree is required}
if [ ! -d "$XNU" ]; then
  echo "run-k60-handoff-host.sh: not a directory: $XNU" >&2
  exit 2
fi
if [ -e "$XNU/bsd/dev/pong_adsp_startup.c" ] ||
   grep -qs "k60_adsp_handoff_publish" "$XNU/bsd/dev/pong_handoff.h" 2>/dev/null; then
  cat >&2 <<'MSG'
run-k60-handoff-host.sh: this tree already contains 0619/0620 (bsd/dev/pong_adsp_startup.c
or k60_adsp_handoff_publish in bsd/dev/pong_handoff.h).
The integration cases apply the 0611 predecessor of the handoff pair themselves, so they
need a tree that predates that series entry; on a newer one they stop with
"canonical source differs", which reads like a code error instead of the wrong input.
Pass a clean pre-0619 tree as the second argument, e.g.
  .../<older-build>/mondrian/ipados-16.6.1-20G81/mondrian/tree/.cache/xnu-work
MSG
  exit 2
fi
mkdir -p "$OUT"
OUT=$(cd "$OUT" && pwd)
exec > >(tee "$OUT/host-tests.log") 2>&1
cd "$REPO"
export PYTHONUTF8=1
CFLAGS=(-std=c11 -O1 -Wall -Wextra -Werror -I drivers/PongPower)
cc "${CFLAGS[@]}" scripts/tests/test-k60-handoff-publish.c \
  drivers/PongPower/K60HandoffPublish.c drivers/PongPower/K60HandoffBuild.c \
  drivers/PongPower/K60Smem.c drivers/PongPower/K60BatteryConfig.c -o "$OUT/publish"
"$OUT/publish"
# This legacy fixture includes the two C implementation units directly.
cc "${CFLAGS[@]}" scripts/tests/test-k60-handoff-build.c \
  drivers/PongPower/K60BatteryConfig.c -o "$OUT/builder"
"$OUT/builder"
OWNER_SOURCES=(drivers/PongPower/K60AdspOwner.c drivers/PongPower/K60AdspOwnerStages.c
  drivers/PongPower/K60AdspMdt.c drivers/PongPower/K60Smem.c
  drivers/PongPower/K60AdspImageReader.c drivers/PongPower/K60Fat.c
  drivers/PongPower/K60HandoffBuild.c drivers/PongPower/K60HandoffPublish.c
  drivers/PongPower/K60BatteryConfig.c)
cc "${CFLAGS[@]}" scripts/tests/test-k60-adsp-owner.c "${OWNER_SOURCES[@]}" -o "$OUT/owner"
"$OUT/owner"
for stage in claim prepare auth build publish; do
  CLAIM_SOURCES=()
  if [ "$stage" = claim ]; then
    CLAIM_SOURCES=(drivers/PongPower/K60AdspBoard.c drivers/PongPower/K60AdspStartup.c
      -Wl,--wrap=k60_smem_alloc)
  fi
  cc "${CFLAGS[@]}" "scripts/tests/test-k60-owner-$stage.c" "${OWNER_SOURCES[@]}" \
    "${CLAIM_SOURCES[@]}" -o "$OUT/owner-$stage"
  "$OUT/owner-$stage"
done
mkdir -p "$OUT/carrier"
python3 scripts/gen-k60-adsp-blob.py --firmware-dir /mnt/e/k60-work/firmware/adsp \
  --output "$OUT/carrier/k60_adsp_blob.s" --dump "$OUT/carrier/k60_adsp_blob.bin"
python3 scripts/check-adsp-blob.py "$OUT/carrier/k60_adsp_blob.s"
cc "${CFLAGS[@]}" scripts/tests/test-k60-adsp-blob.c \
  drivers/PongPower/K60AdspImageReader.c drivers/PongPower/K60Fat.c \
  drivers/PongPower/K60AdspMdt.c -o "$OUT/blob"
"$OUT/blob" /mnt/e/k60-work/firmware/adsp "$OUT/carrier/k60_adsp_blob.bin"
for variant in absent linked zero malformed unsupported; do
  READER_FLAGS=()
  case "$variant" in
    linked) READER_FLAGS=(-DK60_ADSP_TEST_LINKED) ;;
    zero) READER_FLAGS=(-DK60_ADSP_TEST_LINKED_ZERO) ;;
    malformed) READER_FLAGS=(-DK60_ADSP_TEST_LINKED_MALFORMED) ;;
    unsupported) READER_FLAGS=(-DK60_ADSP_TEST_LINKED_UNSUPPORTED) ;;
  esac
  cc "${CFLAGS[@]}" "${READER_FLAGS[@]}" scripts/tests/test-k60-adsp-reader.c "${OWNER_SOURCES[@]}" -o "$OUT/reader-$variant"
  "$OUT/reader-$variant" /mnt/e/k60-work/firmware/adsp "$OUT/carrier/k60_adsp_blob.bin"
done
# Link the actual generated bytes into the host ELF; no test-only carrier parser.
printf '.section .rodata\n.balign 8\n.globl k60_adsp_blob\nk60_adsp_blob:\n.incbin "%s"\n.Ladsp_end:\n.balign 8\n.globl k60_adsp_blob_len\nk60_adsp_blob_len:\n.quad .Ladsp_end-k60_adsp_blob\n.section .note.GNU-stack,"",@progbits\n' "$OUT/carrier/k60_adsp_blob.bin" > "$OUT/carrier/platform-linked.S"
for variant in absent linked; do
  PLATFORM_FLAGS=()
  if [ "$variant" = linked ]; then PLATFORM_FLAGS=(-DK60_ADSP_PLATFORM_TEST_LINKED "$OUT/carrier/platform-linked.S"); fi
  cc "${CFLAGS[@]}" "${PLATFORM_FLAGS[@]}" scripts/tests/test-k60-adsp-platform.c \
    drivers/PongPower/K60AdspPlatform.c "${OWNER_SOURCES[@]}" -o "$OUT/platform-$variant"
  "$OUT/platform-$variant" /mnt/e/k60-work/firmware/adsp "$OUT/carrier/k60_adsp_blob.bin"
done
cc "${CFLAGS[@]}" scripts/tests/test-k60-adsp-startup.c drivers/PongPower/K60AdspStartup.c -o "$OUT/startup"
"$OUT/startup" 1
"$OUT/startup" 2
# Board ownership links ONLY the board, SMEM and startup arbitration. Route A is
# stubbed: resources() must fail closed when the acquisition fails, so a missing
# dependency fails the link (P-223). The real board refusal also runs through
# production owner acquire above, with direct alloc counting. The PAS transport is
# absent for the same reason: "no monitor call" is a link-time fact here.
cc "${CFLAGS[@]}" scripts/tests/test-k60-adsp-board.c drivers/PongPower/K60AdspBoard.c \
  drivers/PongPower/K60Smem.c drivers/PongPower/K60AdspStartup.c -o "$OUT/board"
"$OUT/board"
# The rail parser, the TCS-slot match and the ledger are pure host code; the
# probe itself is kernel-only, so this covers everything up to the map calls.
cc "${CFLAGS[@]}" scripts/tests/test-k60-pmic-rail.c drivers/PongPower/K60PmicRail.c \
  -o "$OUT/rail"
"$OUT/rail"
# Route A: QMP load_state, cmd-db lookup and two TCS4 votes, with every map,
# read and write counted by the test's fake windows.
cc "${CFLAGS[@]}" scripts/tests/test-k60-route-a.c drivers/PongPower/K60AdspRouteA.c \
  drivers/PongPower/K60PmicRail.c -o "$OUT/route-a"
"$OUT/route-a"
python3 scripts/tests/test-k60-adsp-mdt.py --output "$OUT/mdt" --firmware /mnt/e/k60-work/firmware/adsp
python3 scripts/tests/test-k60-notification-qualification.py
python3 scripts/tests/test-battery-units.py
python3 scripts/tests/test-k60-handoff-integration.py --xnu "$XNU"
SDK=$(cd "$XNU/../fakeroot" && pwd)
FRAMEWORK=$SDK/System/Library/Frameworks/Kernel.framework/Versions/A
clang++ -target arm64-apple-ios16.0 -isysroot "$SDK" -mkernel -ffreestanding \
  -fno-builtin -fno-stack-protector -mgeneral-regs-only -DKERNEL=1 \
  -DKERNEL_PRIVATE=1 -DXNU_KERNEL_PRIVATE=1 -DARM64_BOARD_CONFIG_PONG=1 \
  -I "$FRAMEWORK/Headers" -I "$FRAMEWORK/PrivateHeaders" -I drivers/PongPower \
  -fno-exceptions -fno-rtti -std=gnu++17 -fblocks -Wno-deprecated-declarations \
  -fsyntax-only drivers/PongPower/K60HandoffRuntime.cpp drivers/PongPower/K60AdspPlatformNative.cpp
clang -target arm64-apple-ios16.0 -isysroot "$SDK" -mkernel -ffreestanding \
  -fno-builtin -fno-stack-protector -mgeneral-regs-only -DKERNEL=1 \
  -DKERNEL_PRIVATE=1 -DXNU_KERNEL_PRIVATE=1 -DARM64_BOARD_CONFIG_PONG=1 \
  -I "$FRAMEWORK/Headers" -I "$FRAMEWORK/PrivateHeaders" -I drivers/PongPower \
  -std=gnu11 -Wall -Wextra -Werror -Wno-framework-include-private-from-public \
  -fsyntax-only drivers/PongPower/K60AdspBoard.c drivers/PongPower/K60AdspRouteA.c \
  drivers/PongPower/K60PmicRail.c
printf "TESTS OK: arm64 Darwin kernel adapter syntax (not a link)\n"
