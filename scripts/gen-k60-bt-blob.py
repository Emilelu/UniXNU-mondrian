#!/usr/bin/env python3
"""Link the packed Bluetooth firmware container into the kernel.

Why this exists (P-197, measured 2026-11-15): the first S4 carrier put the
container in the payload FAT as <kernel>.gpuaddon and expected the firmware to
copy it into the boot window and publish /chosen/memory-map/GpuAddon.  No
firmware does that.  Platforms/Xiaomi/DarwinBootPkg/Driver/DarwinBoot.c has no
addon case at all ("git grep -ci addon" in uefi-mondrian is zero) and
scripts/unixnu/devicetree.py:339 writes a 16-byte zero placeholder, so the
kernel logs "addon: unusable range 0 0" no matter how correct the container is.
A file being inside the image does not mean the kernel can read it.

The Metal plugin solved the same problem by travelling inside kernel.macho
(scripts/gen-k60-metal-blob.py + patches/xnu/0610).  Bluetooth is 1 MB, 50x
smaller, so it uses the identical shape: the container that
scripts/make-bt-firmware-addon.py already writes is wrapped in an .incbin
assembly file, patches/xnu/0510 lists that file in osfmk/conf/files.arm64, and
bsd/dev/qbt_k60.c reads the linked symbols _k60_bt_blob / _k60_bt_blob_len
before it ever looks at the device tree.

This script only wraps; it does not repack.  Keeping one packer (the one that
checks the firmware whitelist and the manifest hashes) means the bytes that
travel in the kernel are the bytes the packer proved.

Usage:
    scripts/gen-k60-bt-blob.py --assembly --output <k60_bt_blob.s>
    scripts/gen-k60-bt-blob.py --assembly --output <k60_bt_blob.s> \
        --container <pong-bt-firmware.bin>

Without --container the emitted blob is a one-byte stub with length zero, which
is what a build that has no firmware staged must produce: every line builds,
and the kernel falls back to the (empty) GpuAddon range exactly as before, so
other lines see no change.
"""
import argparse
import struct
from pathlib import Path

MAGIC = b'NGPUADD2'
HEADER = 24
ALIGN = 8
MAX_BYTES = 4 * 1024 * 1024
MAX_NAME = 160


def pad(n):
    return (n + ALIGN - 1) & ~(ALIGN - 1)


def parse_container(data):
    """Validate an NGPUADD2 container and return (count, total).

    Mirrors what bsd/dev/qbt_k60.c enforces at runtime (k60_addon_find): a
    header whose total equals the byte count, a non-zero record count, and
    records that stay inside the container.  A container that fails here would
    fail on the device with one log line and no way to recover, so it fails the
    build instead.
    """
    if len(data) < HEADER:
        raise SystemExit('container is %d bytes, shorter than the %d-byte header'
                         % (len(data), HEADER))
    if data[:8] != MAGIC:
        raise SystemExit('container magic is %r, expected %r (not an NGPUADD2 addon)'
                         % (data[:8], MAGIC))
    count, reserved, total = struct.unpack_from('<IIQ', data, 8)
    if count == 0:
        raise SystemExit('container declares zero records')
    if total != len(data):
        raise SystemExit('container header says %d bytes but the file is %d bytes'
                         % (total, len(data)))
    if len(data) > MAX_BYTES:
        raise SystemExit('container is %d bytes; the kernel accepts at most %d'
                         % (len(data), MAX_BYTES))
    off = HEADER
    for index in range(count):
        if off + HEADER > total:
            raise SystemExit('record %d starts past the end of the container' % index)
        name_len, mode, size, packed = struct.unpack_from('<IIQQ', data, off)
        if not 2 <= name_len <= MAX_NAME:
            raise SystemExit('record %d name length %d outside 2..%d'
                             % (index, name_len, MAX_NAME))
        name_bytes = pad(name_len)
        data_bytes = pad(packed)
        record = HEADER + name_bytes + data_bytes
        if off + record > total:
            raise SystemExit('record %d runs past the end of the container' % index)
        if data[off + HEADER + name_len - 1] != 0:
            raise SystemExit('record %d name is not NUL terminated' % index)
        if packed != size:
            raise SystemExit('record %d is compressed (%d -> %d) and this kernel has '
                             'no zlib' % (index, size, packed))
        if (off + HEADER + name_bytes) % ALIGN:
            raise SystemExit('record %d body is not %d-byte aligned' % (index, ALIGN))
        off += record
    if off != total:
        raise SystemExit('records end at %d but the container is %d bytes'
                         % (off, total))
    return count, total


def emit_stub(output):
    lines = ['/* Generated by scripts/gen-k60-bt-blob.py - do not edit. */',
             '/* No container: the kernel falls back to the GpuAddon range. */',
             '.section __DATA,__const',
             '.globl _k60_bt_blob',
             '.p2align 3',
             '_k60_bt_blob:',
             '    .byte 0x00',
             '.p2align 3',
             '.globl _k60_bt_blob_len',
             '.p2align 3',
             '_k60_bt_blob_len:',
             '    .quad 0']
    output.write_text('\n'.join(lines) + '\n')


def emit_container(output, container, count, total):
    lines = ['/* Generated by scripts/gen-k60-bt-blob.py - do not edit. */',
             '/* %d records, %d bytes: %s */' % (count, total, container),
             '.section __DATA,__const',
             '.globl _k60_bt_blob',
             '.p2align 3',
             '_k60_bt_blob:',
             '    .incbin "%s"' % container,
             '.p2align 3',
             '.globl _k60_bt_blob_len',
             '.p2align 3',
             '_k60_bt_blob_len:',
             '    .quad %d' % total]
    output.write_text('\n'.join(lines) + '\n')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--container', type=Path,
                        help='the NGPUADD2 container to embed; omit for an empty blob')
    parser.add_argument('--output', type=Path, required=True,
                        help='the assembly file to write')
    parser.add_argument('--assembly', action='store_true', required=True,
                        help='emit the .incbin assembly carrier (the only supported form)')
    args = parser.parse_args()

    args.output.parent.mkdir(parents=True, exist_ok=True)
    if args.container is None:
        emit_stub(args.output)
        print('%s: empty blob, the kernel keeps using the GpuAddon range' % args.output)
        return 0
    if not args.container.is_file():
        raise SystemExit('container missing: %s' % args.container)
    data = args.container.read_bytes()
    count, total = parse_container(data)
    emit_container(args.output, args.container.resolve(), count, total)
    print('%s: %d records, %d bytes' % (args.output, count, total))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
