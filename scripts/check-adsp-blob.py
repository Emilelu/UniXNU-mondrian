#!/usr/bin/env python3
"""Check the generated K60A carrier and hash its exact assembly payload.

Only the generator's ordered assembly grammar is accepted. The length quad is
outside the payload, while every header, record, name, body and alignment byte
is reconstructed and validated before the SHA-256 is reported.
"""
import hashlib
import re
import struct
import sys
from pathlib import Path

MAGIC = b'K60A'
ALIGN = 8
MODE = 0o644
UINT32_MAX = (1 << 32) - 1
HEADER = struct.Struct('<4sII')
RECORD = struct.Struct('<IIQQ')
GENERATED_COMMENT = '/* Generated by scripts/gen-k60-adsp-blob.py - do not edit. */'
BYTE_LINE = re.compile(r'\.byte\s+(0x[0-9a-fA-F]{2}(?:\s*,\s*0x[0-9a-fA-F]{2})*)')
INCBIN_LINE = re.compile(r'\.incbin\s+"([^"\\\r\n]+)"')
QUAD_LINE = re.compile(r'\.quad\s+([0-9]+)')


def align(n: int) -> int:
    return (n + ALIGN - 1) & ~(ALIGN - 1)


def fits(at: int, size: int, total: int) -> bool:
    return (0 <= at <= total <= UINT32_MAX and
            0 <= size <= total - at and at + size <= UINT32_MAX)


def canonical(name: bytes) -> bool:
    if len(name) != 9 or name[8] != 0 or name[:5] != b'adsp.':
        return False
    tail = name[5:8]
    return tail == b'mdt' or (tail[:1] == b'b' and
                              all(ord('0') <= b <= ord('9') for b in tail[1:]))


def assemble(path: Path):
    """Parse the generator grammar; never ignore an assembly statement."""
    statements = [(i, line.strip())
                  for i, line in enumerate(path.read_text(encoding='utf-8').splitlines(), 1)
                  if line.strip() and line.strip() != GENERATED_COMMENT]
    prefix = ('.data', '.globl _k60_adsp_blob', '.p2align 3', '_k60_adsp_blob:')
    for i, expected in enumerate(prefix):
        if i >= len(statements):
            raise ValueError(f'assembly ended before {expected}')
        line_no, text = statements[i]
        if text != expected:
            raise ValueError(f'line {line_no}: expected {expected}, got {text!r}')

    data = bytearray()
    incbins = []
    declared = None
    state = 'record'
    have_bytes = False

    def append(payload):
        if not fits(len(data), len(payload), UINT32_MAX):
            raise ValueError('assembly payload exceeds UINT32_MAX')
        data.extend(payload)

    def pad():
        append(b'\0' * (align(len(data)) - len(data)))

    for line_no, text in statements[len(prefix):]:
        byte_match = BYTE_LINE.fullmatch(text)
        if state in ('record', 'name') and byte_match:
            append(bytes(int(x.strip(), 16) for x in byte_match[1].split(',')))
            have_bytes = True
        elif state in ('record', 'name') and have_bytes and text == '.p2align 3':
            pad()
            state = 'name' if state == 'record' else 'body'
            have_bytes = False
        elif state == 'body' and (incbin_match := INCBIN_LINE.fullmatch(text)):
            source = Path(incbin_match[1])
            if not source.is_absolute():
                source = path.parent / source
            if not source.is_file():
                raise ValueError(f'line {line_no}: missing .incbin body {source}')
            if not fits(len(data), source.stat().st_size, UINT32_MAX):
                raise ValueError(f'line {line_no}: .incbin exceeds UINT32_MAX')
            body = source.read_bytes()
            incbins.append((len(data), len(body)))
            if len(incbins) > 64:
                raise ValueError(f'line {line_no}: more than 64 .incbin bodies')
            append(body)
            state = 'body padding'
        elif state == 'body padding' and text == '.p2align 3':
            pad()
            state = 'record'
        elif (state == 'record' and not have_bytes and incbins and
              text == '.globl _k60_adsp_blob_len'):
            state = 'length alignment'
        elif state == 'length alignment' and text == '.p2align 3':
            pad()
            state = 'length label'
        elif state == 'length label' and text == '_k60_adsp_blob_len:':
            state = 'length value'
        elif state == 'length value' and (quad_match := QUAD_LINE.fullmatch(text)):
            declared = int(quad_match[1], 10)
            if declared > UINT32_MAX:
                raise ValueError(f'line {line_no}: declared length exceeds UINT32_MAX')
            state = 'done'
        else:
            detail = 'extra statement after length' if state == 'done' else f'in {state}'
            raise ValueError(f'line {line_no}: unexpected assembly {detail}: {text!r}')
    if state != 'done':
        raise ValueError(f'assembly ended in {state}; missing or incomplete length footer')
    return bytes(data), incbins, declared


def check(path: Path):
    problems = []
    data, incbins, declared = assemble(path)
    total = len(data)
    if declared != total:
        problems.append(f'_k60_adsp_blob_len={declared} but the assembly emits '
                        f'{total} bytes (length must include all alignment padding)')
    if not fits(0, HEADER.size, total):
        return problems + [f'header truncated to {total} bytes'], data
    magic, count, reserved = HEADER.unpack_from(data, 0)
    if magic != MAGIC:
        problems.append(f'magic is {magic!r}, not K60A')
    if reserved != 0:
        problems.append(f'reserved header word is {reserved}, not 0')
    if not 1 <= count <= 64:
        return problems + [f'count {count} is outside 1..64'], data
    if count != len(incbins):
        problems.append(f'container says {count} records but the assembly has '
                        f'{len(incbins)} .incbin bodies')

    cursor = HEADER.size
    names = set()
    for idx in range(count):
        record_start = cursor
        if not fits(record_start, RECORD.size, total):
            problems.append(f'[{idx}] record at {record_start} runs past the data')
            break
        name_len, mode, size, packed = RECORD.unpack_from(data, record_start)
        raw_record_end = record_start + RECORD.size
        name_at = align(raw_record_end)
        if not fits(raw_record_end, name_at - raw_record_end, total):
            problems.append(f'[{idx}] record padding runs past the data')
            break
        if any(data[raw_record_end:name_at]):
            problems.append(f'[{idx}] record padding is not zero')
        if name_len != 9:
            problems.append(f'[{idx}] name_len {name_len} is not exactly 9 including NUL')
            break
        if not fits(name_at, name_len, total):
            problems.append(f'[{idx}] name at {name_at} is truncated')
            break
        name_end = name_at + name_len
        body_at = align(name_end)
        if not fits(name_end, body_at - name_end, total):
            problems.append(f'[{idx}] name padding runs past the data')
            break
        name = data[name_at:name_end]
        label = name[:-1].decode('ascii', 'replace') if name.endswith(b'\0') else repr(name)
        if not canonical(name):
            problems.append(f'[{idx}] {label}: name is not canonical adsp.mdt/adsp.bNN with NUL')
        if any(data[name_end:body_at]):
            problems.append(f'[{idx}] {label}: name padding is not zero')
        if mode != MODE:
            problems.append(f'[{idx}] {label}: mode is 0o{mode:o}, not 0o{MODE:o} '
                            f'(the reader reports -8, not malformed -7)')
        if packed != size:
            problems.append(f'[{idx}] {label}: packed_size {packed} != size {size} '
                            f'(no compression; the reader reports -8)')
        if size == 0:
            problems.append(f'[{idx}] {label}: empty body')
        if not fits(body_at, size, total):
            problems.append(f'[{idx}] {label}: body [{body_at},{body_at + size}) runs past the data')
            break
        body_end = body_at + size
        cursor = align(body_end)
        if not fits(body_end, cursor - body_end, total):
            problems.append(f'[{idx}] {label}: body padding runs past the data')
            break
        if any(data[body_end:cursor]):
            problems.append(f'[{idx}] {label}: body padding is not zero')
        if idx >= len(incbins) or incbins[idx] != (body_at, size):
            problems.append(f'[{idx}] {label}: body offset/size does not match its .incbin')
        if name in names:
            problems.append(f'[{idx}] {label}: duplicate name')
        names.add(name)
    if cursor != declared:
        problems.append(f'parsed cursor ends at {cursor} but _k60_adsp_blob_len is {declared}')
    return problems, data


def main(argv) -> int:
    targets = [Path(a) for a in argv[1:]]
    if not targets:
        print('usage: check-adsp-blob.py <generated .s> [...]')
        return 2
    try:
        missing = [t for t in targets if not t.is_file()]
    except OSError as exc:
        print(f'cannot inspect generated carriers: {exc}')
        return 2
    if missing:
        for target in missing:
            print(f'missing generated carrier: {target}')
        return 2
    failed = False
    for target in targets:
        try:
            problems, data = check(target)
        except (OSError, ValueError, struct.error) as exc:
            problems, data = [str(exc)], b''
        if problems:
            failed = True
            print(f'FAIL {target}')
            for problem in problems:
                print(f'   - {problem}')
        else:
            print(f'OK {target}: {len(data)} bytes, %d records, sha256 %s'
                  % (struct.unpack_from('<I', data, 4)[0], hashlib.sha256(data).hexdigest()))
    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
