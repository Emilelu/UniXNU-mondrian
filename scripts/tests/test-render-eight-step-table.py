#!/usr/bin/env python3
"""Exercise the shipped README renderer with branch-independent evidence fixtures."""
import importlib.util
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

SCRIPT = Path(__file__).resolve().parents[1] / "render-eight-step-table.py"
SPEC = importlib.util.spec_from_file_location("eight_step_renderer", SCRIPT)
RENDERER = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(RENDERER)


def fixture(status="active", verify_done=True, official_done=True, device_done=False):
    lines = ['[hardware.bluetooth]', 'name = "触摸（Goodix GT9916R / BERLIN）"',
             'status = "%s"' % status]
    for step in RENDERER.STEPS:
        done = verify_done if step == "verify" else (official_done if step == "official" else (device_done if step == "device" else True))
        lines.extend(['[hardware.bluetooth.step.%s]' % step,
                      'done = %s' % str(done).lower()])
        if step == "verify":
            lines.extend(['local_verified = true', 'static_check = "fixture source:1"',
                          'unit_test = "fixture test:1"', 'artifact_check = "fixture image:1"'])
        if step == "wide":
            lines.extend(['catalog_checked = true', 'catalog_result = "fixture catalog"'])
    return "\n".join(lines) + "\n"


class RendererTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        self.data = self.root / "docs/research/EIGHT-STEPS.toml"
        self.data.parent.mkdir(parents=True)
        self.saved = RENDERER.DATA, RENDERER.UNTRACKED
        RENDERER.DATA, RENDERER.UNTRACKED = str(self.data), []
        self.data.write_text(fixture(), encoding="utf-8")

    def tearDown(self):
        RENDERER.DATA, RENDERER.UNTRACKED = self.saved
        self.tmp.cleanup()

    def render(self, lang="en", **kwargs):
        self.data.write_text(fixture(**kwargs), encoding="utf-8")
        return RENDERER.render(lang)

    def test_a_parked_item_never_claims_ready_even_with_all_steps(self):
        text = self.render(status="parked", device_done=True)
        self.assertIn("Parked (flash gate excludes it)", text)
        self.assertNotIn("Ready to flash", text)
        self.assertNotIn("All eight steps pass", text)
        self.assertIn("已暂停", self.render("zh", status="parked"))

    def test_verify_done_false_cannot_be_overridden_by_three_strings(self):
        entry = {"done": False, "local_verified": True, "static_check": "source",
                 "unit_test": "test", "artifact_check": "image"}
        self.assertEqual(RENDERER.cell(entry, "verify"), "❌")
        self.assertNotIn("Ready to flash", self.render(verify_done=False))

    def test_missing_an_earlier_step_cannot_be_ready(self):
        self.assertNotIn("Ready to flash", self.render(official_done=False))

    def test_an_active_item_with_seven_complete_steps_retains_readiness(self):
        self.assertIn("Ready to flash (⑦ verified)", self.render())

    def test_english_names_and_explanation_are_translated(self):
        text = self.render()
        self.assertIn("Touch (Goodix GT9916R / BERLIN)", text)
        self.assertIn("Generated by", text)
        self.assertNotIn("触摸", text)
        self.assertNotIn("表格由", text)
        self.assertGreater(len(text.splitlines()), 4)

    def invoke(self, flag):
        env = dict(os.environ, K60_REPO=str(self.root), PYTHONDONTWRITEBYTECODE="1")
        return subprocess.run([sys.executable, str(SCRIPT), flag], env=env,
                              capture_output=True, text=True)

    def test_apply_and_check_cover_both_readmes(self):
        for name in ("README.md", "README_EN.md"):
            (self.root / name).write_text("# Fixture\n<!-- EIGHT-STEP-TABLE:BEGIN -->\nold\n<!-- EIGHT-STEP-TABLE:END -->\n", encoding="utf-8")
        applied = self.invoke("--apply")
        self.assertEqual(applied.returncode, 0, applied.stderr)
        checked = self.invoke("--check")
        self.assertEqual(checked.returncode, 0, checked.stdout + checked.stderr)
        english = self.root / "README_EN.md"
        english.write_text(english.read_text(encoding="utf-8").replace("Ready to flash", "STALE"), encoding="utf-8")
        stale = self.invoke("--check")
        self.assertNotEqual(stale.returncode, 0)
        self.assertIn("README_EN.md", stale.stdout)
        self.assertEqual(self.invoke("--apply").returncode, 0)
        (self.root / "README.md").unlink()
        missing = self.invoke("--check")
        self.assertNotEqual(missing.returncode, 0)
        self.assertIn("README.md", missing.stdout)


if __name__ == "__main__":
    unittest.main()
